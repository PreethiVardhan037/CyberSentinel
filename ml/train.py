def _parse_args() -> argparse.Namespace:
    p = argparse.ArgumentParser(description="Train CyberSentinel ML model")
    p.add_argument("--mode", choices=["demo", "real"], default="demo",
                   help="Training mode: 'demo' uses synthetic data, 'real' uses CIC-IDS2017")
    p.add_argument("--data-path", default=None,
                   help="Path to CIC-IDS2017 CSV (required for --mode real)")
    p.add_argument("--test-size", type=float, default=0.2)
    p.add_argument("--seed",      type=int,   default=42)
    return p.parse_args()


def main() -> None:
    args = _parse_args()

    if args.mode == "real":
        if not args.data_path:
            sys.exit("[train] --data-path is required for --mode real")
        if not os.path.exists(args.data_path):
            sys.exit(f"[train] File not found: {args.data_path}")
        df = _load_real_data(args.data_path)
    else:
        df = _load_demo_data()

    pipeline, metrics = train(df, test_size=args.test_size, seed=args.seed)
    save_artifacts(pipeline, metrics, mode=args.mode)
    print("[train] Done.")


if __name__ == "__main__":
    main()
